/**
 * Purpose: the first load of the club directory into the hosted database. Turns the club list
 *          the demo uses (src/data/clubs.ts, copied from uwomeds.com, 2026-11-05) into SQL.
 * Usage:   node scripts/clubs-to-sql.mjs > clubs.sql   (Node 22.18+ reads the .ts files)
 * Writes:  clubs (slug, name, description, campuses, categories) and their links. Not the
 *          execs: those in clubs.ts are invented samples, and real execs come from the roster.
 * Safe to run again: it inserts only while the clubs table is empty, so it never overwrites
 * what execs and admins change later. The deploy runs it after the migrations.
 */
import { CLUBS } from '../src/data/clubs.ts';
import { CATEGORIES_BY_SLUG } from '../src/data/club-categories.ts';

const SLUG = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const URL_OK = /^https?:\/\/[^\s]+$/;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (xs, type) => `${q(`{${xs.join(',')}}`)}::public.${type}[]`;

const rows = [];
const links = [];
for (const c of CLUBS) {
  if (!SLUG.test(c.slug)) throw new Error(`bad slug: ${c.slug}`);
  const cats = c.categories ?? CATEGORIES_BY_SLUG[c.slug] ?? [];
  rows.push(`(${q(c.slug)}, ${q(c.name.trim())}, ${q(c.description)}, ${arr(c.campuses, 'campus')}, ${arr(cats, 'club_category')})`);
  c.links.filter((u) => URL_OK.test(u) && u.length <= 500).slice(0, 6)
    .forEach((u, i) => links.push(`(${q(c.slug)}, ${i + 1}, ${q(u)})`));
}

console.log(`-- Generated by scripts/clubs-to-sql.mjs: ${rows.length} clubs, ${links.length} links.
begin;
create temp table first_load on commit drop as select not exists (select 1 from public.clubs) as empty;

insert into public.clubs (slug, name, description, campuses, categories)
select * from (values
  ${rows.join(',\n  ')}
) as v(slug, name, description, campuses, categories)
where (select empty from first_load);
${links.length ? `
insert into public.club_links (club_id, position, url)
select c.id, v.position, v.url from (values
  ${links.join(',\n  ')}
) as v(slug, position, url)
join public.clubs c on c.slug = v.slug
where (select empty from first_load);
` : ''}
select case when (select empty from first_load) then 'Loaded ${rows.length} clubs.' else 'Clubs already loaded; nothing changed.' end as result;
commit;`);
